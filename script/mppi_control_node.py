    def exceed_ob(self, ob_):
        # 获取障碍物的圆心坐标和半径
        ob_vec = np.array([ob_[0], ob_[1]])  # 障碍物圆心
        r = ob_[2]  # 圆的半径
        
        # 获取机器人当前位置
        curr_vec = self.Jackal_states[:2]  # 当前机器人的位置

        dist_robot_obstacle =  np.linalg.norm(curr_vec - ob_vec) - r - self.r
        if (dist_robot_obstacle <= 0):
           print("------- robot_obstacle crush !!!-------")
           print(f"crush dist: {dist_robot_obstacle}")
        dist_robot_obstacle = max(dist_robot_obstacle, 1e-6)

        return dist_robot_obstacle <= self.check_dist
    
