    ''' @brief: Retrieving the controllers' parameters, the costmap information, and summary of the performance'''
    def test_summary(self):
        if self.distanceToGoal > 0.5:
            self.local_minima = True
        else:
            self.local_minima = False
            # test_summary 方法生成控制器的性能摘要信息。
            # distanceToGoal > 0.5 表明机器人未能足够接近目标，设置 self.local_minima = True 表示可能陷入局部最小值。

        #self.map_info = 'cost-map'
        control_history = np.array(self.control_history) # 将 control_history 转换为 numpy 数组，以便方便地访问和处理控制数据。

        # 检查 control_history 是否有超过 max_linear_velocity 或 max_angular_velocity 的值，如果超出则设置 violate_ctrl_const 为 True，表示违反了速度约束。
        if max(control_history[:, 0]) > self.max_linear_velocity or max(
                control_history[:, 1]) > self.max_angular_velocity:
            self.violate_ctrl_const = True
        else:
            self.violate_ctrl_const = False

        # 将 state_history 中的 x 和 y 位置提取出来，并传递给 uls.pathLength(x, y) 计算机器人的行驶路径长度 pathLength。
        x, y = [s[0] for s in self.state_history
                ], [s[1] for s in self.state_history]
        self.pathLength = uls.pathLength(x, y)
        # Compute the avarage excution time of MPPI over all iterations
        # 计算 MPPI 在所有迭代中的平均执行时间 av_t_mppi。
            # 若 av_t_mppi 小于控制频率（1 / self.hz）的倒数，则设置 real_time_mppi 为 True，表示 MPPI 实时控制成功。
        self.av_t_mppi = np.mean(np.array(self.mppi_time_history)[20:])
        if self.av_t_mppi < 1 / float(self.hz):
            self.real_time_mppi = True
        else:
            self.real_time_mppi = False

        self.var_v =  uls.var_v(self.control_history)
        self.average_v =  uls.average_v(self.control_history)
        # self.var_v = 0
        # print(f"self.control_history:{self.control_history}")
        # 调用 uls.testSummaryMPPI 方法生成测试摘要，保存控制器的参数、性能指标等信息，包括初始状态 init_pose、目标 targets、控制器限制（最大线速度、角速度等）和代价权重 weights。
        
        obs_num = int(len(self.ob_state_history[0]))


        # save_results 将历史数据（状态、目标状态、代价和控制）保存在 results_rootpath 以供后续查看。
        uls.save_results(self.state_history, self.desired_state_history,
                         self.state_cost_history, self.min_cost_history,
                         self.control_history, self.mppi_time_history,
                         self.results_rootpath)

        uls.save_obs_results(obs_num, self.results_rootpath, self.ob_state_history, self.ob_slack_history)

        uls.save_time_results(self.results_rootpath, self.mppi_time_history)


        mindist = uls.cla_mindist(self.r, obs_num, self.results_rootpath)          

        uls.testSummaryMPPI(
            self.init_pose, self.targets, self.max_linear_velocity,
            self.max_angular_velocity, self.time_horizon,
            self.hz, self.weights, self.num_trajectories, self.R,
            self.Sigma_du, self.exploration_variance, self.lambda_,
            self.slack_weight,self.std_n_sla,self.atau,
            self.beta_1, self.beta_2, self.beta_3, self.check_dist,
            self.SG_window, self.SG_PolyOrder, self.dist_type, self.cbf_type, 
            self.local_minima, self.violate_ctrl_const, self.pathLength,self.var_v,self.average_v,mindist,
            self.av_t_mppi, self.real_time_mppi, self.firstrun_time, self.run_time, self.results_rootpath)



