    """ @brief: Checking out whether the desired pose is reached or not
            check_goal_reached 方法用于检查机器人是否已经达到目标点。 """
    def check_goal_reached(self, state, target):
        """
        Check if the position and orientation are close enough to the target.
        If this is the case, set the current goal to succeeded.
        """
        # 发布移动命令
            # 创建一个布尔消息cmd_move，并根据当前状态与全局路径最后一个点的距离决定是否发布移动命令。
        cmd_move = Bool()
        cmd_move.data = True
        # position_tolerance 和 orientation_tolerance 分别表示位置和方向容忍度。
        position_tolerance = self.minimumDistance - 0.1
        orientation_tolerance = 0.15

        # 计算 distanceToGoal，即当前状态与目标位置的距离。
        distanceToGoal = np.sqrt(
            np.square(target[1] - state[1]) + np.square(target[0] - state[0]))
        sys.stdout.write("distanceToGoal: %.3f\n" % distanceToGoal)
        # 若 distanceToGoal 小于位置容忍度，且角度误差小于方向容忍度，则调用 set_succeeded() 标记目标为已成功到达。

        if distanceToGoal < position_tolerance:
            # self._as.set_succeeded()
            sys.stdout.write("Reached Goal!!!!!!!!!----!-----!")
            cmd_move.data = False
            if not self.firstrun:
                self.firstrun = True
                self.firstrun_time = time.time() - self.start_time
                sys.stdout.write("firstrun_time: %.3f\n" % self.firstrun_time)
        print(cmd_move.data)
        return cmd_move.data
            
    """ @brief: Handling the robot's heading angle, based on each quarter, for performing a heading navigation 
            headingAngle 方法用于计算到目标的最优朝向。"""
    def headingAngle(self, current_state, desired_state):
        # delta_x 和 delta_y 分别为 x 和 y 坐标上的偏差，通过 arctan2 计算最优航向 desired_heading。
        delta_x = desired_state[0] - current_state[0]
        delta_y = desired_state[1] - current_state[1]
        desired_heading = np.arctan2(delta_y, delta_x)
        # 根据 current_state[2] 和 desired_heading 的差异判断当前朝向，考虑到不同象限的角度范围。
        # 调整 desired_heading 以确保其在合理范围内，并返回 desired_heading 和对应的 case（用于调试或控制）。
        if ((desired_heading - current_state[2]) <
            (-np.pi / 2.0)) and ((desired_heading - current_state[2]) >
                                 (-3.0 * np.pi / 2.0)):
            desired_heading = desired_heading - np.pi
            case = 1
        elif (((desired_heading - current_state[2]) > (np.pi / 2))
              and ((desired_heading - current_state[2]) <
                   (3.0 * np.pi / 2.0))):
            desired_heading = desired_heading + np.pi
            case = 2
        elif ((desired_heading - current_state[2]) < (-3.0 * np.pi / 2.0)):
            desired_heading = desired_heading + 2 * np.pi
            case = 3
        elif ((desired_heading - current_state[2]) > (3.0 * np.pi / 2.0)):
            desired_heading = desired_heading - 2 * np.pi
            case = 4
        else:
            desired_heading = desired_heading
            case = 5
        return desired_heading, case

    """ @brief: The primary function for running the MPPI algorithm 
            run_mppi 是主控制循环，通过 MPPI 算法计算最优路径。"""
    def run_mppi(self):
            # 若里程计数据有效，则设置初始位置 init_pose。
        if self.Jackal_states != None:
            print("The MPPI controller got first odometry message")
            self.init_pose = self.Jackal_states
            self.targets = np.copy(self.desired_pose)
        self.start_time = time.time()
        while self.check_goal_reached(self.Jackal_states, self.targets):
            """ Update the obstacle map based on the costmap acquired by the sensor """

                # 读取当前状态和目标位置。
            self.state = np.copy(self.Jackal_states)
            self.targets = np.copy(self.desired_pose)

            print(f"self.state:= {self.state}")
            print(f"self.targets:= {self.targets}")

                # 读取虚拟障碍的信息
            self.obs_cb()

                # 计算当前状态与目标位置之间的距离。
            self.distanceToGoal = np.sqrt(
                np.square(self.targets[1] - self.state[1]) +
                np.square(self.targets[0] - self.state[0]))
            
                # 如果无需朝向控制（without_heading），则直接使用当前 yaw 角度。
            if self.without_heading:
                if self.distanceToGoal > self.minimumDistance:
                    self.targets[2] = self.state[2]
                else:
                    self.targets[2] = self.desired_pose[2]
            else:
                # 若需控制朝向，则调用 headingAngle 方法设置 yaw，使机器人始终面向目标。
                desired_heading, case = self.headingAngle(
                    self.state, self.targets)
                if self.distanceToGoal > self.minimumDistance:
                    self.targets[2] = desired_heading
                else:
                    self.targets[2] = self.desired_pose[2]
                # Increase the weight of the 3rd state (yaw) so that the robot heads towards the goal ASAP
                self.weights[2] = 60.0


            # 加入 VO 引导采样






            # 开始计时并调用 compute_control 方法计算最优控制输入 u，记录执行时间 t_mppi。
            start = time.time()
            #################开始计时并调用 compute_control 方法计算最优控制输入 u，记录执行时间 t_mppi #############
            if not self.soft_cbf:
                u, optimal_U, sample_U, normalizer, min_cost = self.jackal_controller.compute_control(
                    self.state,
                    [self.std_n, self.R, self.weights, self.targets, self.obstacle.data, self.obstacle.num])
                
            else:
                # print(f"self.U := {self.jackal_controller.U}") 
                u, optimal_U, sample_U, ob_u, normalizer, min_cost = self.jackal_controller.compute_control(
                    self.state,
                    [self.std_n, self.R, self.weights, self.targets], 
                        [self.obstacle.data, self.obstacle.num, self.obstacle.id, 
                            self.r_sla, self.std_n_sla, self.obstacle.U, self.obstacle.state_sla])    
                

            if (u[0] > self.max_linear_velocity):
                u[0] = self.max_linear_velocity
            
            if (u[0] < - self.max_linear_velocity):
                u[0] = - self.max_linear_velocity
            

            if (u[1] > self.max_angular_velocity):
                u[1] = self.max_angular_velocity
            
            if (u[1] < - self.max_angular_velocity):
                u[1] = - self.max_angular_velocity
            

            # The excution time of MPPI
            t_mppi = time.time() - start
            if self.soft_cbf:
                # 更新障碍物松弛变量状态
                self.obstacle.state_sla = self.obstacle.update_state(self.obstacle.state_sla, ob_u)           
                self.sla_state_cost = self.obstacle.cost(self.obstacle.state_sla,
                                        [self.obstacle.weights, self.obstacle.target_sla])
                self.ob_slack_history.append(np.copy(self.obstacle.state_sla))   
                print(f"state_sla:{self.obstacle.state_sla}")
                print(f"self.sla_state_cost:{self.sla_state_cost}")                
                    
            
            # Record the costs
            # 计算状态代价和控制代价，将结果保存至 state_cost 和 control_cost
            costs = self.robot.cost(self.state, u,
                                    [self.weights, self.targets, self.R])
            self.state_cost = costs[0]
            self.control_cost = costs[1]


            # 计算总成本
            total_cost = self.state_cost + self.control_cost + self.sla_state_cost
            # print(f"self.state_cost:{self.state_cost}")
            # print(f"min_cost:{min_cost}")

            # 打印总成本
            # print("Total Cost:", total_cost)

            # Record and update the state, and the mppi excution time
            # 将当前控制输入 u、状态、代价和执行时间等历史信息存储以供分析和调试。
            
            self.control_history.append(u)
            self.state_history.append(np.copy(self.state))

            self.optimal_U_history.append(np.copy(optimal_U))
            sample_U = sample_U.reshape(self.draw_num_traj, self.N, self.control_dim)
            self.sample_U_history.append(np.copy(sample_U))

            self.ob_state_history.append(np.copy(self.obstacle.all_cur_state))

            self.desired_state_history.append(np.copy(self.targets))
            self.state_cost_history.append(self.state_cost)
            self.min_cost_history.append(min_cost)
            self.control_cost_history.append(self.control_cost)
            if t_mppi*1000 > 10:
                print(f"t_mppi:{t_mppi*1000}")
                t_mppi = 0.0
            self.mppi_time_history.append(t_mppi* 1000) # 转毫秒
            self.run_time = len(self.mppi_time_history) * 0.1
            if(self.run_time>50):
                break


            # 如果 print_out 为真，则输出当前状态、执行时间和控制输入，以便调试。
            if self.print_out:
                sys.stdout.write(
                    "Current States: (%f, %f, %f), t_mppi: %f \n" %
                    (self.state[0], self.state[1],
                        self.state[2] * 180 / np.pi, t_mppi))
                sys.stdout.write("U: (%f, %f) \n" % (u[0], u[1]))
                print(
                    "------------------------------------------------------"
                )
                sys.stdout.flush()
            if np.isnan(np.sum(self.state)):
                print("Breaking MPPI due to numerical errors")
                self.fail = True
                break
            
            # 更新 機器人狀態
            self.Jackal_states = self.robot.update_state(self.state, u)
            # print(f"Jackal_states:{self.Jackal_states}")
            # 更新 机器人状态
            self.obstacle.update_cur_state_virtual(self.obstacle.virtual_ob_state)
            # print(f"obstacle_states:{self.obstacle.virtual_ob_state}")

